"""Validate the incident-training catalog and generate the browser data."""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parent
payload = json.loads((ROOT / 'compiled-catalog.json').read_text(encoding='utf-8'))
codes = json.loads((ROOT / 'scenario-codes.json').read_text(encoding='utf-8'))
cards = payload['scenarios']
materials = {'tomato', 'pepper', 'meat', 'shrimp', 'cheese', 'bacon'}

assert len(cards) == len({scenario['id'] for scenario in cards}) == 5
assert [scenario['code'] for scenario in cards] == ['A', 'B', 'C', 'D', 'E']
assert codes == {scenario['id']: scenario['code'] for scenario in cards}
assert len(payload['groups']) == 1
for group in payload['groups']:
    assert len([scenario for scenario in cards if scenario['group'] == group['id']]) == group['count']

for scenario in cards:
    step_ids = [step['id'] for step in scenario['steps']]
    assert len(step_ids) == len(set(step_ids)) == len(materials), scenario['id']
    assert scenario['recipe'] == step_ids, scenario['id']
    assert scenario['accepted'][0] == scenario['recipe'], scenario['id']
    for step in scenario['steps']:
        assert all(step[key].strip() for key in ('label', 'shortLabel', 'reason')), scenario['id']
    assert scenario.get('cloudDiff', '').strip(), scenario['id']
    for order in scenario['accepted']:
        assert len(order) == len(set(order)) == len(step_ids), scenario['id']
        assert set(order) == set(step_ids), scenario['id']
    assert scenario['title'].strip() and scenario['summary'].strip() and scenario['debrief'].strip()

output = 'globalThis.BOOTH_CONTENT = ' + json.dumps(payload, ensure_ascii=False, indent=2) + ';\n'
(ROOT / 'dist' / 'scenarios.js').write_text(output, encoding='utf-8')
print('Validated and generated 5 cloud incident scenarios (A-E).')

# Embed fonts as data URIs so dist/index.html also works when opened directly (file://),
# where browsers block font files loaded through url() as cross-origin requests.
import base64
fonts = [
    ('Jua', 'Jua-Regular.ttf', 'font/ttf', 'truetype', 'font-weight:400'),
    ('Pretendard', 'PretendardVariable.woff2', 'font/woff2', 'woff2', 'font-weight:45 920'),
]
rules = []
for family, filename, mime, fmt, weight in fonts:
    data = base64.b64encode((ROOT / 'dist' / 'assets' / filename).read_bytes()).decode('ascii')
    rules.append(f"@font-face{{font-family:'{family}';src:url(data:{mime};base64,{data}) format('{fmt}');{weight};font-style:normal;font-display:swap}}")
(ROOT / 'dist' / 'fonts.css').write_text('/* Generated by build_web_data.py */\n' + '\n'.join(rules) + '\n', encoding='utf-8')
print('Generated dist/fonts.css with embedded fonts.')
